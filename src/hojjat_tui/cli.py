"""CLI entry point for HOJJAT TUI.

Supports:
- Console script entry point: `hojjat-tui`
- Python module entry point: `python -m hojjat_tui`
- Management commands via: `python manage.py <command>`
- Project entry point: `python manage.py` (generated by `hojjat-tui init`)
"""

import runpy
import sys
from pathlib import Path
from typing import List, Optional

from hojjat_tui import __version__, run
from hojjat_tui.management import main as management_main

MANAGE_FILE = "manage.py"


def _find_manage_py() -> Optional[Path]:
    """Locate the project's manage.py in the current working directory.

    Returns the Path to manage.py if found, otherwise None.
    Only looks in CWD — does not blindly search the filesystem.
    """
    candidate = Path.cwd() / MANAGE_FILE
    if candidate.is_file():
        return candidate
    return None


def _execute_manage_py(manage_file: Path) -> None:
    """Execute manage.py inside the current Python process.

    Uses runpy.run_path() with run_name="__main__" so that:
    - The registry and TUI share the same process and memory.
    - Module-level decorators (@hojjat_function) execute and register.
    - The project root is on sys.path so imports resolve correctly.
    """
    project_root = manage_file.parent
    root_str = str(project_root)
    if root_str not in sys.path:
        sys.path.insert(0, root_str)

    runpy.run_path(str(manage_file), run_name="__main__")


def main(argv: Optional[List[str]] = None):
    """Main entry point for the console script.

    If no arguments are provided, locates and executes the project's
    manage.py (via runpy in the current process), then starts the TUI.

    If arguments are provided, delegates to management commands.

    Usage:
        hojjat-tui          # Start TUI (executes manage.py then run())
        hojjat-tui run      # Run a registered function
        hojjat-tui --version # Show version
    """
    if argv is None:
        argv = sys.argv[1:]

    if not argv:
        # No arguments — start the TUI via the project's manage.py.
        manage_file = _find_manage_py()
        if manage_file is None:
            print("[error] No manage.py found in the current directory.")
            print("")
            print("  To create a new HOJJAT TUI project, run:")
            print("      hojjat-tui init")
            print("")
            print("  Then run: hojjat-tui")
            sys.exit(1)

        # Execute manage.py in the current process so decorators register
        # functions in the shared in-memory registry and manage.py starts
        # the TUI via its `if __name__ == "__main__": run()` block.
        # Do NOT call run() here — that would start a second TUI instance.
        _execute_manage_py(manage_file)
        return

    if "--version" in argv or "-V" in argv:
        print(f"hojjat-tui version {__version__}")
        return

    # Delegate to management commands (init, run, check, test, etc.)
    management_main(argv)


def cli_main():
    """Console script entry point."""
    main()


def module_main():
    """Python module entry point: python -m hojjat_tui."""
    main()


if __name__ == "__main__":
    module_main()
